"""Turn a recorded simulation run (program_*.json from toolchange_demo) into an Annin HMI 6.0 program (.ar4).

Only joint moves ("Move R") are written, so the robot repeats the exact joint path validated in simulation,
independent of the HMI's tool frame and of the URDF/HMI 7 mm model difference.

usage: ros2 run ar4tc_toolchanger export_hmi [program.json] [-o out.ar4] [--force]
       (default input: newest ~/ar4tc_reports/program_*.json)
"""
import argparse
import glob
import json
import os
import time

import numpy as np

from . import annin_kinematics as ak
from . import annin_protocol as ap
from . import hmi_program as hp


def build_lines(prog):
    cfg, h = prog["config"], prog["config"]["hmi"]
    lock_on = h["lock_on_is_locked"]
    lines = [
        "##AR4 tool changer - generated by ar4tc export_hmi from a simulation run (do not edit by hand)",
        f"##ar4tc config: {prog['config_name']}",
        f"##generated {time.strftime('%Y-%m-%d %H:%M')}; simulation result: {prog['result']}",
        "##Joint moves only (Move R). Start with the area clear; the first line moves to HOME.",
        f"##Tool lock: Out {'On' if lock_on else 'Off'} = {h['lock_output']} locks, "
        f"Out {'Off' if lock_on else 'On'} = {h['lock_output']} releases (edit hmi.lock_output in the config)",
    ]
    for t, d in cfg["tools"].items():
        lines.append(f"##slot {t}: {d['label']}")
    q = np.array(ap.ros_to_annin(prog["start"]))
    n_moves = 0
    for it in prog["items"]:
        if it["type"] == "move":
            pts = np.array([ap.ros_to_annin(p) for p in it["points"]])
            if it["step"] == "home":  # MoveIt stops within its goal tolerance; write the exact HOME angles
                pts[-1] = ap.ros_to_annin(cfg["home"])
            _, kept = ap.simplify(it["times"], np.vstack([q, pts[1:]]), h["path_tolerance_deg"])
            sp = h["speed_dock"] if it["kind"] == "dock" else h["speed_free"]
            lines.append(f"##{it['step']}")
            for p in kept[1:]:
                lines.append(hp.move_r(p, sp, h["acc"], h["dcc"], h["ramp"]))
                n_moves += 1
            q = kept[-1]
            if it["kind"] == "dock" and (it["step"].startswith("onto") or it["step"].endswith("into cradle")):
                T = ak.fk(q)
                x, y, z = T[:3, 3]
                cx, cy, cz = T[:3, 3] + T[:3, :3] @ np.array([0, 0, 1000.0 * cfg["mating_offset"][2]])
                lines.append(f"##  docking pose, HMI coords (tool frame 0): flange X {x:.1f} Y {y:.1f} Z {z:.1f} mm; "
                             f"coupling face X {cx:.1f} Y {cy:.1f} Z {cz:.1f} mm")
        elif it["type"] in ("couple", "release"):
            locking = it["type"] == "couple"
            lines += [f"##TC {it['type'].upper()} {it['tool']}",
                      hp.out(locking == lock_on, h["lock_output"]),
                      hp.wait(h["lock_wait_s"])]
    lines.append("##END - robot at HOME")
    return lines, n_moves


def main():
    a = argparse.ArgumentParser()
    a.add_argument("program", nargs="?")
    a.add_argument("-o", "--out")
    a.add_argument("--force", action="store_true", help="export even if the simulation run did not finish DONE")
    args, _ = a.parse_known_args()
    src = args.program or max(glob.glob(os.path.expanduser("~/ar4tc_reports/program_*.json")), key=os.path.getmtime)
    with open(src) as f:
        prog = json.load(f)
    if prog["result"] != "DONE" and not args.force:
        raise SystemExit(f"{src}: simulation result {prog['result']} - refusing to export (use --force)")
    lines, n = build_lines(prog)
    out = args.out or os.path.join(os.path.dirname(src), "AR4TC " + os.path.basename(src)[8:-5] + ".ar4")
    hp.write(out, lines)
    print(f"wrote {out}: {n} Move R lines, {len(lines)} lines total (from {src})")


if __name__ == "__main__":
    main()
