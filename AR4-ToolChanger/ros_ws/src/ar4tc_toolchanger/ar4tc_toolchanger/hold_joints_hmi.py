"""Turn an exported HMI 6.0 program (Move R) into a DRY-RUN version that never moves the held joints
(default J4, J5, J6), optionally looping forever (Tab Number 1 ... Jump Tab-1; stop it in the HMI).

Every Move R target is converted to its flange position (Annin kinematics, HMI coordinates) and re-solved
with J1-J3 only; the straight docking moves are subdivided every --step-mm so the flange still follows a
near-straight line. Held joints are written with exactly the --start values. Without J5 the tool can't stay
vertical, so the tool tilts and a real coupling is NOT possible: lock outputs are written as comments only.

usage: python3 -m ar4tc_toolchanger.hold_joints_hmi "<in>.ar4" --start J1..J6 -o "<out>.ar4" [--loop]
"""
import argparse
import time

import numpy as np

from . import annin_kinematics as ak
from . import annin_protocol as ap
from . import hmi_program as hp
from .goto_pose_hmi import check_path, solve, steps


def main():
    a = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    a.add_argument("program")
    a.add_argument("--start", nargs=6, type=float, required=True, metavar="Jn",
                   help="current joint angles exactly as the HMI shows them (deg)")
    a.add_argument("--hold", nargs="+", type=int, default=[4, 5, 6])
    a.add_argument("--loop", action="store_true", help="repeat until stopped in the HMI")
    a.add_argument("--step-mm", type=float, default=10.0, help="subdivision of straight moves (default 10 mm)")
    a.add_argument("--max-jump", type=float, default=20.0, help="max joint change between two points (deg)")
    a.add_argument("--min-z", type=float, default=150.0)
    a.add_argument("--pause", type=float, default=1.0, help="Wait Time in place of each lock/release")
    a.add_argument("-o", "--out", required=True)
    args = a.parse_args()

    q0 = np.array(args.start)
    hold = sorted(set(args.hold))
    free = [i for i in range(6) if i + 1 not in hold]
    ops = hp.parse(args.program)
    home_src = next(o.q_deg for o in ops if o.kind == "move")

    lines = [
        "##DRY RUN tool change, held joints - generated by ar4tc hold_joints_hmi (do not edit by hand)",
        f"##source: {args.program.split('/')[-1]}; generated {time.strftime('%Y-%m-%d %H:%M')}",
        f"##HELD STILL: J{' J'.join(map(str, hold))}. ONLY RUN IF THE HMI SHOWS EXACTLY: "
        + " ".join(f"J{i + 1} {q0[i]:.3f}" for i in range(6)),
        "##Flange visits the same dock positions as the source, but the tool TILTS (no J5): no real coupling.",
        "##No dock or tools in place. Lock outputs are comments only. J1-J3 calibrated, hand on the E-stop.",
    ]
    if args.loop:
        lines += ["##LOOPS FOREVER: stop it with the HMI stop button", "Tab Number 1"]

    q, x_prev, problems, n_moves, n_src = q0.copy(), ak.xyz(q0), [], 0, 0
    for o in ops:
        if o.kind == "comment":
            if not o.text.startswith(("##BEGINNING", "##AR4 tool changer", "##ar4tc config", "##generated",
                                      "##Joint moves", "##Tool lock", "##END")):
                lines.append(o.text)
        elif o.kind in ("couple", "release"):
            lines += [f"##DRY {o.kind.upper()} {o.tool} (no output switched)", hp.wait(args.pause)]
        elif o.kind == "out":
            continue
        elif o.kind == "wait":
            continue                                  # replaced by the pause above
        elif o.kind == "move":
            n_src += 1
            is_home = np.allclose(o.q_deg, home_src)
            x_goal = ak.xyz(q0) if is_home else ak.xyz(o.q_deg)
            straight = o.speed <= 10                  # exporter: Sp 10 = straight docking move
            n = max(1, int(np.ceil(np.linalg.norm(x_goal - x_prev) / args.step_mm))) if straight else 1
            for s in np.linspace(0, 1, n + 1)[1:]:
                if is_home and s == 1:
                    q1 = q0.copy()
                else:
                    q1 = solve(x_prev + (x_goal - x_prev) * s, q, free)
                    if q1 is None:
                        problems.append(f"line {o.line_no}: X {x_goal.round(1).tolist()} unreachable with held joints")
                        break
                    q1 = np.array([float(f"{v:.3f}") for v in q1])
                    q1[[h - 1 for h in hold]] = q0[[h - 1 for h in hold]]
                if (jump := np.max(np.abs(q1 - q))) > args.max_jump and straight:
                    problems.append(f"line {o.line_no}: joint jump {jump:.1f} deg inside a straight move")
                if not ap.within_limits(q1):
                    problems.append(f"line {o.line_no}: {q1.tolist()} outside firmware limits")
                problems += [f"line {o.line_no}: {p}" for p in check_path(q, q1, args.min_z)]
                lines.append(hp.move_r(q1, o.speed, 20, 20, 100))
                n_moves += 1
                q = q1
            x_prev = x_goal
    if np.any(steps(q) != steps(q0)) and args.loop:
        problems.append("program does not end at the start pose, so it can't loop")
    held_ok = all(float(hp._MOVE_R.match(l).group(h)) == q0[h - 1]
                  for l in lines if l.startswith("Move R") for h in hold)
    if not held_ok:
        problems.append("a Move R line changes a held joint")
    if args.loop:
        lines += ["##back to the top", "Jump Tab-1"]
    lines.append("##END")
    if problems:
        for p in problems:
            print("  PROBLEM:", p)
        raise SystemExit("REFUSED: no program written")
    hp.write(args.out, lines)
    print(f"{n_src} source Move R -> {n_moves} Move R, held J{hold}, loop={args.loop}")
    print(f"wrote {args.out}  RESULT: OK")


if __name__ == "__main__":
    main()
